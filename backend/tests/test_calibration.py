def test_targeted_exposure_is_kept_out_of_the_blind_rating(app):  # noqa: F811
    with app.app_context():
        question = Question.query.filter_by(section="Logical Reasoning").first()
        for index in range(6):
            calibration.record_response(
                student(f"blind-{index}"), question, True, exposure=calibration.EXPOSURE_BLIND
            )
        blind_after = question.calibration.blind_rating
        for index in range(6):
            calibration.record_response(
                student(f"targeted-{index}"), question, False, exposure=calibration.EXPOSURE_TARGETED
            )
        db.session.flush()
        row = question.calibration
        assert row.responses == 12
        assert row.blind_responses == 6
        assert row.targeted_responses == 6
        # The blind rating saw none of the six targeted responses.
        assert row.blind_rating == pytest.approx(blind_after)
        # …and the naive rating did, so the two have separated. That gap is the
        # measurement of the distortion.
        reading = calibration.signal(question, row, centre=0.0)
        assert reading["selection_bias_gap"] is not None
        assert abs(reading["selection_bias_gap"]) > 0.05


