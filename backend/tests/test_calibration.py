"""Question difficulty: the empty state, the estimator, and whether it predicts.

Three kinds of test here, and the third is the one that matters.

The first kind holds the *absence* in place. All 6,886 questions used to carry a
literal difficulty of 3, and the failure mode this module is defending against
is somebody helpfully filling the column back in — so there is a test that reads
the application source and fails if anything assigns to `published_difficulty`.

The second kind checks the arithmetic: that a correct answer makes an item look
easier and its answerer look stronger, that the step shrinks as evidence
accumulates, and that the provenance ladder cannot be climbed without evidence.

The third runs the estimator over a synthetic corpus generated by a *different*
model and asserts that the ratings predict held-out responses better than a
model that knows the student and nothing about the question. A difficulty
estimate that fails that is not a difficulty estimate, and this project has a
long enough history of instruments agreeing with whatever they are pointed at
that the check belongs in the suite rather than in a report nobody re-runs.
"""

