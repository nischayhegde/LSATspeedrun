def test_the_exposure_draw_is_stable_and_reserves_a_quarter_of_slots():
    first = calibration.exposure_draw("u1", "s1", 3)
    assert calibration.exposure_draw("u1", "s1", 3) == first
    assert first["policy"] in {"random", "targeted"}

    draws = [calibration.exposure_draw("u1", f"s{index}", index % 8) for index in range(4000)]
    random_share = sum(draw["policy"] == "random" for draw in draws) / len(draws)
    assert calibration.RANDOM_HOLDOUT_SHARE - 0.03 < random_share < calibration.RANDOM_HOLDOUT_SHARE + 0.03
    # The propensity on the row is the probability of the arm that happened, so
    # a later inverse-propensity fit does not have to reconstruct the scheme.
    for draw in draws[:50]:
        expected = (
            calibration.RANDOM_HOLDOUT_SHARE
            if draw["policy"] == "random"
            else 1 - calibration.RANDOM_HOLDOUT_SHARE
        )
        assert draw["propensity"] == pytest.approx(expected)


