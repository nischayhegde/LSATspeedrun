def test_the_ingest_path_never_states_a_difficulty():
    """`seed.py` used to write `question.difficulty = 3` on every row.

    The upstream datasets carry no difficulty column at any revision, so there
    is nothing to write, and writing one anyway is what put a constant in front
    of a language model for the entire life of the application.
    """
    source = (APP_DIR / "seed.py").read_text(encoding="utf-8")
    assert "difficulty = 3" not in source
    assert "question.published_difficulty" not in source


def test_nothing_in_the_application_writes_a_published_difficulty():
    """`published_difficulty` means "the test maker stated one" and nothing else.

    An estimate written here would be indistinguishable from a real rating
    afterwards, which is precisely the property that made the old column
    worthless. The estimate has its own table and its own provenance.
    """
    offenders = []
    for path in sorted(APP_DIR.glob("*.py")):
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
            stripped = line.strip()
            if stripped.startswith("#"):
                continue
            if "published_difficulty" not in stripped or "=" not in stripped:
                continue
            # The column declaration itself is the one legitimate assignment.
            if "db.Column" in stripped:
                continue
            # A keyword argument or a comparison is fine; an assignment is not.
            head = stripped.split("=", 1)[0]
            if head.rstrip().endswith("published_difficulty"):
                offenders.append(f"{path.name}:{number}: {stripped}")
    assert not offenders, (
        "something assigns a published difficulty. Only an importer of a real "
        f"published rating may do that, and there is not one: {offenders}"
    )


