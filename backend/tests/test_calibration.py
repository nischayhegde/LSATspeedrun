def test_the_response_model_reduces_to_plain_elo_without_a_guessing_floor():
    assert calibration.expected_correct(0.0, 0.0, 0.0) == pytest.approx(0.5)
    assert calibration.expected_correct(1.0, 0.0, 0.0) == pytest.approx(calibration.logistic(1.0))
    # With a floor, a hopeless student still has the floor.
    assert calibration.expected_correct(-8.0, 0.0, 0.2) == pytest.approx(0.2, abs=1e-3)
    assert calibration.expected_correct(0.0, 0.0, 0.2) == pytest.approx(0.6)


def test_a_correct_answer_makes_the_item_easier_and_the_student_stronger():
    match = calibration.Match(theta=0.0, difficulty=0.0, is_correct=True, guess=0.2)
    assert match.next_difficulty(0.0) < 0.0
    assert match.next_theta(0.0) > 0.0
    missed = calibration.Match(theta=0.0, difficulty=0.0, is_correct=False, guess=0.2)
    assert missed.next_difficulty(0.0) > 0.0
    assert missed.next_theta(0.0) < 0.0


def test_a_correct_answer_on_a_hopeless_item_barely_moves_anything():
    """Most of a right answer on an impossible item is the guess, not knowledge.

    Plain Elo cannot express that: it reads the same outcome as an enormous
    upset and runs the rating away. The q/p factor is what stops it.
    """
    hopeless = calibration.Match(theta=-3.0, difficulty=3.0, is_correct=True, guess=0.2)
    plausible = calibration.Match(theta=0.0, difficulty=0.0, is_correct=True, guess=0.2)
    # Same accumulated information on both, so only the response differs.
    hopeless_move = abs(hopeless.next_difficulty(1.0) - 3.0)
    plausible_move = abs(plausible.next_difficulty(1.0) - 0.0)
    assert hopeless_move < plausible_move / 4
    # The surprise is larger on the hopeless item and the move is smaller, which
    # is the whole difference between this and plain Elo.
    assert hopeless.surprise > plausible.surprise


def test_the_step_shrinks_as_evidence_accumulates():
    first = calibration.item_step_size(0.0)
    later = calibration.item_step_size(10.0)
    much_later = calibration.item_step_size(100.0)
    assert first > later > much_later
    assert much_later < 0.02
    # A student's step is floored, because ability keeps moving and a rating
    # that stops moving stops tracking it.
    assert calibration.learner_step_size(1e6) == pytest.approx(
        1.0 / (calibration.LEARNER_PRIOR_PRECISION + calibration.LEARNER_INFORMATION_CAP)
    )


def test_an_uninformative_response_carries_almost_no_information():
    """Somebody who was always going to get it right says nothing about the item."""
    matched = calibration.response_information(0.0, 0.0, 0.2)
    mismatched = calibration.response_information(4.0, -4.0, 0.2)
    assert matched > mismatched * 50


def test_ratings_cannot_run_away():
    difficulty = 0.0
    for _ in range(500):
        match = calibration.Match(theta=3.0, difficulty=difficulty, is_correct=True, guess=0.2)
        difficulty = match.next_difficulty(0.0)  # never let the step decay
    assert -calibration.RATING_LIMIT <= difficulty <= calibration.RATING_LIMIT


