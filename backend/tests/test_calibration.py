def test_the_rating_predicts_held_out_responses_better_than_knowing_only_the_student():
    """The claim this whole module rests on, run as a test rather than a report.

    The corpus is generated by a 2PL model with per-item guessing floors and
    ability that drifts upward — three ways of being different from what the
    estimator assumes. The `learner` baseline is given the student's identity
    and nothing about the question, so everything the item rating is worth
    appears as the gap between it and `elo`.

    The thresholds are set well below the measured values (log loss 0.609
    against 0.642, AUC 0.694) so that ordinary drift does not fail the suite,
    but a rating that has stopped carrying signal will.
    """
    from scripts.calibration_lab import evaluate, simulate

    simulation = simulate(items=250, learners=100, responses_per_learner=60, seed=4242)
    result = evaluate(simulation.responses, holdout=0.3, seed=99)
    scores = {row["model"]: row for row in result["models"]}

    assert scores["elo"]["log_loss"] < scores["learner"]["log_loss"]
    assert scores["elo"]["log_loss"] < scores["global"]["log_loss"]
    assert result["elo_vs_learner_log_loss"] > 0.015
    assert scores["elo"]["auc"] > 0.65
    # The ratings order the items the way the held-out responses do.
    assert result["rating_vs_holdout_difficulty_spearman"] > 0.4


def test_the_information_scaled_step_beats_every_constant_it_replaced():
    """Complexity has to pay for itself, so the step rule is measured too.

    `K = 1/(prior + ΣI)` is two functions and an accumulator more than plain
    Elo's constant. It is worth having only if it predicts better than the best
    constant anyone would have picked, run over the same responses in the same
    order.
    """
    from scripts.calibration_lab import evaluate, simulate

    simulation = simulate(items=250, learners=100, responses_per_learner=60, seed=4242)
    result = evaluate(
        simulation.responses, holdout=0.3, seed=99, fixed_k_arms=(0.1, 0.2, 0.4, 0.8)
    )
    scores = {row["model"]: row for row in result["models"]}
    constants = [row for name, row in scores.items() if name.startswith("elo_fixed_k_")]
    assert len(constants) == 4
    assert scores["elo"]["log_loss"] < min(row["log_loss"] for row in constants)
    assert scores["elo"]["auc"] > max(row["auc"] for row in constants)


def test_the_rating_recovers_the_difficulties_that_generated_the_data():
    from scripts.calibration_lab import recovery, replay, simulate

    simulation = simulate(items=250, learners=100, responses_per_learner=100, seed=4242)
    recovered = recovery(replay(simulation.responses), simulation.truth)
    assert recovered["mean_responses_per_item"] > 30
    # A Rasch estimator cannot recover a 2PL difficulty exactly, so this is a
    # rank claim rather than an identity one.
    assert recovered["spearman"] > 0.8
    assert abs(recovered["bias"]) < 0.1


def test_holding_the_random_slice_out_reproduces_the_rating_from_unbiased_exposure_alone():
    """What `blind_rating` buys, measured.

    Under a selector that always targets, there is no unbiased slice at all and
    nothing to check the naive rating against. Reserving a quarter of slots
    produces a second estimate built only from exposure that could not depend on
    difficulty — noisier, because it has a quarter of the data, and that is the
    price of being able to check at all.
    """
    from scripts.calibration_lab import recovery, replay, simulate

    without = simulate(items=200, learners=100, responses_per_learner=80, seed=77, targeting=1.0)
    assert recovery(replay(without.responses, unbiased_only=True), without.truth)["items"] == 0

    with_slice = simulate(
        items=200, learners=100, responses_per_learner=80, seed=77, targeting=1.0, random_holdout=0.25
    )
    checkable = recovery(replay(with_slice.responses, unbiased_only=True), with_slice.truth)
    assert checkable["items"] > 150
    assert checkable["spearman"] > 0.5
