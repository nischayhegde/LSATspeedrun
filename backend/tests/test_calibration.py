def student(handle: str) -> str:
    """A real account, because `learner_ratings.user_id` is a real foreign key.

    A rating that could be filed against a user id nobody owns is a rating that
    outlives the account it describes, which is both a data-protection problem
    and a way for an ability estimate to be silently attributed to the wrong
    person.
    """
    existing = User.query.filter_by(email=f"{handle}@example.test").first()
    if existing:
        return existing.id
    user = User(email=f"{handle}@example.test", display_name=handle)
    db.session.add(user)
    db.session.flush()
    return user.id


