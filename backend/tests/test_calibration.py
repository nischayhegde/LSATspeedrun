    client = app.test_client()
    headers = login(client, "calibrate@example.test")
    create_game(client, headers)
    run_session(app, client, headers, "calibrate", size=4, correct=3)

    with app.app_context():
        rated = QuestionCalibration.query.all()
        assert len(rated) == 4, "every answered question should have picked up a rating"
        assert all(row.responses == 1 for row in rated)
        assert all(row.origin == "responses" for row in rated)
        assert all(row.status == "provisional" for row in rated)
        # Three right and one wrong, so three items moved down and one up.
        assert sum(row.rating < 0 for row in rated) == 3
        assert sum(row.rating > 0 for row in rated) == 1

        # Exposure travelled from the served item onto the attempt.
        assert {item.exposure_policy for item in SessionItem.query.all()} == {"blind"}
        assert {attempt.exposure_policy for attempt in Attempt.query.all()} == {"blind"}
        assert all(row.blind_responses == 1 for row in rated)

        # One ability rating per section the run touched, never one per student:
        # weakness at Reading Comprehension must not make Logical Reasoning items
        # look easy.
        learners = LearnerRating.query.all()
        assert {row.scope for row in learners} <= {"Logical Reasoning", "Reading Comprehension"}
        assert len({row.user_id for row in learners}) == 1
        assert sum(row.responses for row in learners) == 4


